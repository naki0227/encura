#!/usr/bin/env python3
"""Verify researched content and write it as a dated SQL migration.

The daily content routine (docs/CONTENT_ROUTINE.md) researches candidates and
saves them as JSON; this script decides what is publishable:

  * exhibitions: the official page must name the exhibition; the venue is
    geocoded from its address with the GSI address search
  * Today's Art: the artwork must have an image on Wikidata/Commons credited
    to the same artist
  * news: the source page must name the subject of the story
  * venues (museums listed in the app's venue search): the official site
    must name the museum; the address is geocoded with the GSI address search

Accepted items become supabase/migrations/<UTC timestamp>_content_<JST date>.sql.
The SQL is idempotent (ON CONFLICT ...), so re-running a day is harmless.

    python scripts/content/build_migration.py candidates.json [--out-dir supabase/migrations] [--offline]

--offline skips page/geocode/image checks (tests only).
Prints a Markdown report for the pull request.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from common import geo, images, web  # noqa: E402
from content import sql  # noqa: E402

JST = dt.timezone(dt.timedelta(hours=9))
LOOKAHEAD_DAYS = 60
MAX_EVENT_DAYS = 400
DAILY_DAYS_AHEAD = 14
NEWS_KEYWORDS = ("展覧会", "新発見・修復", "美術館", "作品・作家", "特集")
GENERATED_MARK = "-- generated by scripts/content/build_migration.py"


def clean(value) -> str:
    """Collapse whitespace; keep the text as written (full-width marks stay)."""
    return re.sub(r"\s+", " ", str(value or "")).strip()


def venue_name(value) -> str:
    """Venue names are a unique key, so width and spacing are unified."""
    return clean(unicodedata.normalize("NFKC", str(value or "")))


def parse_date(value) -> dt.date | None:
    try:
        return dt.date.fromisoformat(clean(value))
    except ValueError:
        return None


ITEM_MARK = "-- item: "


@dataclass
class Report:
    accepted: list[str] = field(default_factory=list)
    rejected: list[str] = field(default_factory=list)
    items: list[str] = field(default_factory=list)

    def ok(self, kind: str, label: str, detail: str = "") -> None:
        self.accepted.append(f"{kind}: {label}" + (f" ({detail})" if detail else ""))
        # One line per published item, read back by published.py so later
        # runs can skip what is already live.
        self.items.append(f"{ITEM_MARK}{kind} | {label.replace(chr(10), ' ')}")

    def no(self, kind: str, label: str, reason: str) -> None:
        self.rejected.append(f"{kind}: {label} — {reason}")

    def markdown(self) -> str:
        lines = [f"### Accepted ({len(self.accepted)})"] + [f"- {a}" for a in self.accepted]
        lines += ["", f"### Rejected ({len(self.rejected)})"] + [f"- {r}" for r in self.rejected]
        return "\n".join(lines)


class Checks:
    """Network checks, swappable in tests."""

    def __init__(self, offline: bool = False):
        self.offline = offline

    def page_naming(self, phrase: str, urls: list[str]) -> str | None:
        if self.offline:
            return next((u for u in urls if web.is_http_url(u)), None)
        return web.find_page_mentioning(phrase, urls)

    def geocode(self, address: str):
        # Offline runs (CI's SQL check) still exercise the location columns.
        return (35.6812, 139.7671) if self.offline else geo.geocode(address)

    def artwork_image(self, titles: list[str], artists: list[str]) -> str | None:
        if self.offline:
            return "https://upload.wikimedia.org/offline.jpg"
        return images.find_artwork_image(titles, artists)


# --- exhibitions ------------------------------------------------------------------

def event_statements(items, today: dt.date, checks: Checks, report: Report) -> list[str]:
    out = []
    for item in items or []:
        title, venue = clean(item.get("title")), venue_name(item.get("venue"))
        start, end = parse_date(item.get("start_date")), parse_date(item.get("end_date"))
        label = f"{title or '?'} @ {venue or '?'}"
        if not title or not venue or not start or not end:
            report.no("exhibition", label, "missing title, venue or dates")
            continue
        if end < today or start > end or (end - start).days > MAX_EVENT_DAYS \
                or start > today + dt.timedelta(days=LOOKAHEAD_DAYS):
            report.no("exhibition", label, f"dates out of range ({start} - {end})")
            continue
        urls = [clean(item.get("official_url"))] + [clean(u) for u in item.get("sources") or []]
        verified = checks.page_naming(title, urls)
        if not verified:
            report.no("exhibition", label, "no page names this exhibition")
            continue
        address = clean(item.get("venue_address"))
        coords = checks.geocode(address) if address else None
        out.append(f"""insert into public.venues (name, address, location)
values ({sql.text(venue)}, {sql.text(address or None)}, {sql.point(coords)})
on conflict (name) do update set
    address = coalesce(public.venues.address, excluded.address),
    location = coalesce(public.venues.location, excluded.location);
insert into public.events (title, venue, venue_id, location, start_date, end_date, description_json, source_url)
select {sql.text(title)}, v.name, v.id, v.location, {sql.date(start)}, {sql.date(end)},
       {sql.jsonb_summary(clean(item.get("summary")))}, {sql.text(verified)}
from public.venues v where v.name = {sql.text(venue)}
on conflict (title, venue) do update set
    start_date = excluded.start_date,
    end_date = excluded.end_date,
    description_json = excluded.description_json,
    source_url = excluded.source_url,
    venue_id = excluded.venue_id,
    location = coalesce(excluded.location, public.events.location);""")
        report.ok("exhibition", label, f"{start} - {end}, {'located' if coords else 'no coordinates'}, {verified}")
    return out


# --- Today's Art --------------------------------------------------------------------

def daily_statement(items, checks: Checks, report: Report) -> list[str]:
    rows = []
    seen = set()
    for item in items or []:
        title, artist, content = clean(item.get("title")), clean(item.get("artist")), clean(item.get("content"))
        label = f"{title or '?'} / {artist or '?'}"
        if not title or not artist or not content:
            report.no("daily art", label, "missing title, artist or text")
            continue
        if web.normalize(title) in seen:
            continue
        seen.add(web.normalize(title))
        image = checks.artwork_image([clean(item.get("title_en")), title], [clean(item.get("artist_en")), artist])
        if not image:
            report.no("daily art", label, "no image of this work by this artist on Wikidata")
            continue
        rows.append(f"({len(rows) + 1}, {sql.text(title)}, {sql.text(artist)}, {sql.text(image)}, {sql.text(content)})")
        report.ok("daily art", label)
    if not rows:
        return []
    # Dates are picked when the migration runs: the free days from today (JST)
    # through the next two weeks, skipping works that were already shown.
    return [f"""with candidate (n, title, artist, image_url, content) as (
    values
    {(","+chr(10)+"    ").join(rows)}
), fresh as (
    select c.*, row_number() over (order by c.n) as k
    from candidate c
    where not exists (select 1 from public.daily_columns d where d.title = c.title)
), free_day as (
    select day::date as display_date, row_number() over (order by day) as k
    from generate_series((now() at time zone 'Asia/Tokyo')::date,
                         (now() at time zone 'Asia/Tokyo')::date + {DAILY_DAYS_AHEAD}, interval '1 day') as day
    where not exists (select 1 from public.daily_columns d where d.display_date = day::date)
)
insert into public.daily_columns (title, artist, image_url, content, display_date)
select f.title, f.artist, f.image_url, f.content, d.display_date
from fresh f join free_day d using (k)
on conflict (display_date) do nothing;"""]


# --- venues -------------------------------------------------------------------------

def venue_statements(items, checks: Checks, report: Report) -> list[str]:
    out = []
    for item in items or []:
        name, address = venue_name(item.get("name")), clean(item.get("address"))
        website = clean(item.get("website_url"))
        label = name or "?"
        if not name or not address or not web.is_http_url(website):
            report.no("venue", label, "missing name, address or website")
            continue
        verified = checks.page_naming(name, [website])
        if not verified:
            report.no("venue", label, "official site does not name this museum")
            continue
        coords = checks.geocode(address)
        if not coords:
            report.no("venue", label, f"address could not be geocoded: {address}")
            continue
        out.append(f"""insert into public.venues (name, address, location, website_url)
values ({sql.text(name)}, {sql.text(address)}, {sql.point(coords)}, {sql.text(verified)})
on conflict (name) do update set
    address = coalesce(public.venues.address, excluded.address),
    location = coalesce(public.venues.location, excluded.location),
    website_url = coalesce(public.venues.website_url, excluded.website_url);""")
        report.ok("venue", label, address)
    return out


# --- news ---------------------------------------------------------------------------

def news_statements(items, checks: Checks, report: Report) -> list[str]:
    out = []
    for item in items or []:
        title, summary, content = clean(item.get("title")), clean(item.get("summary")), clean(item.get("content"))
        source = clean(item.get("source_url"))
        label = title or "?"
        if not title or not summary or not content or not web.is_http_url(source):
            report.no("news", label, "missing title, text or source URL")
            continue
        subject = clean(item.get("subject"))
        phrase = subject if len(web.normalize(subject)) >= 3 else title
        verified = checks.page_naming(phrase, [source])
        if not verified:
            report.no("news", label, f"source page does not mention {phrase!r}")
            continue
        art = item.get("artwork") or {}
        image = ""
        if art.get("title_en") and art.get("artist_en"):
            image = checks.artwork_image([clean(art["title_en"])], [clean(art["artist_en"])]) or ""
        keyword = clean(item.get("keyword"))
        if keyword not in NEWS_KEYWORDS:
            keyword = "美術館"
        out.append(f"""insert into public.trending_articles (title, summary, content, image_url, keyword, source_url)
values ({sql.text(title)}, {sql.text(summary)}, {sql.text(content)}, {sql.text(image)}, {sql.text(keyword)}, {sql.text(verified)})
on conflict (source_url) do nothing;""")
        report.ok("news", label, verified)
    return out


def build(candidates: dict, now: dt.datetime, checks: Checks) -> tuple[str | None, Report]:
    report = Report()
    today = now.astimezone(JST).date()
    statements = (
        venue_statements(candidates.get("venues"), checks, report)
        + event_statements(candidates.get("exhibitions"), today, checks, report)
        + daily_statement(candidates.get("daily_art"), checks, report)
        + news_statements(candidates.get("news"), checks, report)
    )
    if not statements:
        return None, report
    header = [GENERATED_MARK, f"-- researched {now.astimezone(JST):%Y-%m-%d %H:%M} JST", *report.items, ""]
    return "\n".join(header) + "\n\n".join(statements) + "\n", report


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("candidates")
    parser.add_argument("--out-dir", default=str(Path(__file__).resolve().parents[2] / "supabase" / "migrations"))
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()

    candidates = json.loads(Path(args.candidates).read_text(encoding="utf-8"))
    now = dt.datetime.now(dt.timezone.utc)
    body, report = build(candidates, now, Checks(offline=args.offline))
    print(report.markdown())
    if body is None:
        print("\nNothing verifiable; no migration written.")
        return 1
    path = Path(args.out_dir) / f"{now:%Y%m%d%H%M%S}_content_{now.astimezone(JST):%Y%m%d}.sql"
    path.write_text(body, encoding="utf-8")
    print(f"\nWrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
