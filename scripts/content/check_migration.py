#!/usr/bin/env python3
"""Gate for automatically merged content pull requests.

A content PR may only add new supabase/migrations/*_content_*.sql files
written by build_migration.py, and those files may only insert into (or
upsert) the public content tables. Anything else needs a human review.

    python scripts/content/check_migration.py <changed file> [...]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from content.build_migration import GENERATED_MARK  # noqa: E402

NAME = re.compile(r"^supabase/migrations/\d{14}_content_\d{8}\.sql$")
TABLES = (
    "public.venues", "public.events", "public.daily_columns", "public.trending_articles",
    "public.art_movements", "public.movement_links", "public.artworks", "public.artists",
)
FORBIDDEN = re.compile(
    r"\b(drop|alter|delete|truncate|grant|revoke|create|copy|execute|call|do|function|"
    r"policy|role|security|set\s+role|pg_\w+|auth\.|storage\.|vacuum|comment)\b",
    re.I,
)


def strip_literals(sql: str) -> str:
    """Remove comments and string literals so keywords inside text don't count.

    One left-to-right pass, so "--" inside a string is text, not a comment.
    """
    out, i, n = [], 0, len(sql)
    while i < n:
        if sql.startswith("--", i):
            end = sql.find("\n", i)
            i = n if end == -1 else end
        elif sql.startswith("/*", i):
            end = sql.find("*/", i + 2)
            i = n if end == -1 else end + 2
        elif sql[i] == "'":
            j = i + 1
            while j < n:
                if sql[j] == "'":
                    if j + 1 < n and sql[j + 1] == "'":
                        j += 2
                        continue
                    break
                j += 1
            out.append("''")
            i = j + 1
        else:
            out.append(sql[i])
            i += 1
    return "".join(out)


def statement_problems(sql: str) -> list[str]:
    problems = []
    bare = strip_literals(sql)
    if "$" in bare:
        problems.append("dollar quoting is not allowed")
    for raw in bare.split(";"):
        stmt = " ".join(raw.split()).lower()
        if not stmt:
            continue
        # "on conflict ... do update/do nothing" is the only allowed use of "do".
        check = re.sub(r"\bon conflict\b[^;]*?\bdo (update set|nothing)", "on conflict", stmt)
        if not (check.startswith("insert into ") or check.startswith("with ")):
            problems.append(f"statement must be an INSERT: {stmt[:60]}")
            continue
        targets = re.findall(r"\binsert into ([\w.]+)", check)
        if not targets or any(t not in TABLES for t in targets):
            problems.append(f"inserts into a table that is not content: {targets}")
        if re.search(r"\bupdate\s+[\w.]+\s+set\b", check):
            problems.append("UPDATE statements are not allowed")
        hit = FORBIDDEN.search(check)
        if hit:
            problems.append(f"forbidden keyword {hit.group(0)!r}")
    return problems


def check_file(path: str, root: Path) -> list[str]:
    if not NAME.match(path):
        return [f"{path}: content PRs may only add supabase/migrations/<timestamp>_content_<date>.sql"]
    text = (root / path).read_text(encoding="utf-8")
    if not text.startswith(GENERATED_MARK):
        return [f"{path}: not generated by build_migration.py"]
    return [f"{path}: {p}" for p in statement_problems(text)]


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parents[2]
    if not argv:
        print("no files given", file=sys.stderr)
        return 1
    problems = [p for path in argv for p in check_file(path, root)]
    for p in problems:
        print(p)
    if not problems:
        print(f"OK: {len(argv)} content migration(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
